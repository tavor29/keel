export function titanRisks(team: TitanTeam, base: Pick<Risk, 'programId' | 'sharedWithGuestIds' | 'followerIds' | 'createdAt' | 'updatedAt'>): Risk[] {
  return RISKS.map((r, i) => ({
    ...base,
    sharedWithGuestIds: [],
    followerIds: [],
    id: `itm_titan_${r.key}`,
    code: r.code,
    workstreamId: TITAN_WS[r.ws],
    order: 900 + i,
    type: 'risk',
    title: r.title,
    description: r.description,
    status: r.status ?? 'in_progress',
    probability: r.probability,
    impact: r.impact,
    trigger: r.trigger,
    mitigation: r.mitigation,
    contingency: r.contingency,
    ownerId: r.owner === 'lead' || !r.owner ? team.byWs[r.ws][0]! : r.owner,
  }));
}
